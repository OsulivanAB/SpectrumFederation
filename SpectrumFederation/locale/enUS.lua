-- Resolve a locale key with an English fallback when the table is incomplete.
function ns.LocaleText(key, default)
	local value = L[key]
	if type(value) == "string" and value ~= "" then
		return value
	end
	if type(default) == "string" then
		return default
	end
	return tostring(key or "")
end
